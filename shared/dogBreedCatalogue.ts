/**
 * Every dog breed MoeGo offers, so a new dog can be picked rather than typed.
 *
 * Exported from MoeGo's own pet-options endpoint on 21/10/2026 — the list
 * behind its "Pet breed" dropdown — and filtered to dogs (`petTypeId: 1`).
 * Cats and the other pet types MoeGo carries are deliberately left out:
 * this salon grooms dogs, and offering "Abyssinian" in a dog's breed box
 * is how a wrong record gets made.
 *
 * ## It is a STARTING list, not a closed one
 *
 * The breed field stays free text. 357 of the breeds already on file here
 * came across in the MoeGo import and some of them are this salon's own
 * shorthand — "Malt X Shih", "B.Collie X Poodle" — which no catalogue
 * would ever contain. `pets.listBreeds` offers the salon's own breeds
 * first, commonest first, then everything here that is not already in
 * use. Typing something new still works and joins the list.
 *
 * ## Why a constant and not a table
 *
 * These names are the same for every salon, so a table would be 630 rows
 * of identical data per tenant plus a migration to keep them in step. The
 * per-tenant part — which breeds a salon actually uses — is already
 * derived from its own dogs.
 *
 * A handful of entries are MoeGo-side oddities rather than breeds ("B.C
 * X", "zueta bolonka", "White shephard"). They are kept as exported
 * rather than curated: they are what the salon will recognise, and
 * second-guessing somebody else's catalogue is how a breed quietly goes
 * missing.
 */

