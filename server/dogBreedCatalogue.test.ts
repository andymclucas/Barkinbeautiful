import { describe, it, expect } from "vitest";
import { DOG_BREED_CATALOGUE, DOG_BREED_CATALOGUE_KEYS } from "@shared/dogBreedCatalogue";

/**
 * MoeGo's breed list, exported 21/10/2026 from its pet-options endpoint.
 */

describe("the catalogue itself", () => {
  it("carries MoeGo's dog breeds", () => {
    expect(DOG_BREED_CATALOGUE.length).toBe(630);
  });

  it("holds no duplicates, in any casing", () => {
    expect(DOG_BREED_CATALOGUE_KEYS.size).toBe(DOG_BREED_CATALOGUE.length);
  });

  it("is free of blanks and untrimmed entries", () => {
    for (const breed of DOG_BREED_CATALOGUE) {
      expect(breed).toBe(breed.trim());
      expect(breed.length).toBeGreaterThan(1);
    }
  });

  it("contains the breeds this salon actually grooms", () => {
    // The commonest dogs here. If an export ever drops these, the picker
    // is worse than the text box it replaced.
    for (const breed of ["Cavoodle", "Maltese", "Shih Tzu", "Border Collie",
      "Labradoodle", "Poodle (Toy)", "Poodle (Miniature)", "Bichon Frise"]) {
      expect(DOG_BREED_CATALOGUE_KEYS.has(breed.toLowerCase())).toBe(true);
    }
  });

  it("includes the breed MoeGo had and Groomigo did not", () => {
    // Spotted on MoeGo's calendar and absent from the 357 already on file.
    expect(DOG_BREED_CATALOGUE_KEYS.has("poodle (medium)")).toBe(true);
  });

  it("leaves cats out", () => {
    // petTypeId 2 is a cat. Offering Abyssinian in a dog's breed box is
    // how a wrong record gets made.
    for (const cat of ["Abyssinian", "Maine Coon", "Ragdoll", "Siamese"]) {
      expect(DOG_BREED_CATALOGUE_KEYS.has(cat.toLowerCase())).toBe(false);
    }
  });

  it("drops the junk entry MoeGo carries", () => {
    // MoeGo's list contains a breed literally named ".".
    expect(DOG_BREED_CATALOGUE).not.toContain(".");
  });

  it("is sorted, so the tail of the picker is navigable", () => {
    // Plain lowercase comparison, not localeCompare: the file is
    // generated by sorting on the lowercased name, and localeCompare
    // orders punctuation differently, which would fail on entries like
    // "B.C X" for no useful reason.
    for (let i = 1; i < DOG_BREED_CATALOGUE.length; i++) {
      const previous = DOG_BREED_CATALOGUE[i - 1].toLowerCase();
      const current = DOG_BREED_CATALOGUE[i].toLowerCase();
      expect(previous <= current).toBe(true);
    }
  });
});
